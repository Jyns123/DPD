import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {writeFileSync,mkdirSync} from 'node:fs';
const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:5173';
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw new Error('Prueba exclusiva para servidor local.');
const first=await fetch(base+'/api/analytics');assert.equal(first.status,200);
const tag=first.headers.get('etag');assert.ok(tag);const firstData=await first.json();
const same=await fetch(base+'/api/analytics',{headers:{'If-None-Match':tag}});
assert.equal(same.status,304);assert.equal((await same.text()).length,0);
const event={id:randomUUID(),visitorId:randomUUID(),type:'page_view'};
const post=await fetch(base+'/api/analytics',{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify(event)});assert.equal(post.status,201);
const changed=await fetch(base+'/api/analytics',{headers:{'If-None-Match':tag}});
assert.equal(changed.status,200);assert.notEqual(changed.headers.get('etag'),tag);
const changedData=await changed.json();assert.ok(changedData.events.some(row=>row.id===event.id));
const home=await fetch(base);
assert.equal(home.headers.get('x-content-type-options'),'nosniff');
assert.equal(home.headers.get('x-frame-options'),'SAMEORIGIN');
const report={executedAt:new Date().toISOString(),checks:5,status:'passed',checksDescription:['Lectura inicial con ETag','Sin cambios devuelve304 sincuerpo','Nuevo evento invalida ETag','Evento nuevo incluido','Cabeceras de protección presentes'],firstPayloadBytes:Buffer.byteLength(JSON.stringify(firstData)),unchangedPayloadBytes:0,note:'Actividad sintética de prueba en base desechable. No mide concurrencia ni seguridad de producción.'};
mkdirSync('tests/results',{recursive:true});writeFileSync('tests/results/analytics-cache.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
