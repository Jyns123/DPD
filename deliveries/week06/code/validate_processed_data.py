"""Validate Week 6 processed CSV outputs with only the Python standard library."""
import csv
import math
from collections import Counter, defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
PROCESSED = ROOT / "deliveries" / "week06" / "data" / "processed"
OUTPUT = PROCESSED / "validation_report.md"

FEATURE_STORE = PROCESSED / "listings_feature_store.csv"

REQUIRED_COLUMNS = [
    "listing_id",
    "source",
    "district",
    "ubigeo",
    "price_soles",
    "area_m2",
    "price_per_m2",
    "rooms",
    "bathrooms",
    "parking",
    "district_median_price_m2",
    "baseline_price_soles",
    "opportunity_score_baseline",
    "crime_index_zone",
    "urban_convenience_index",
    "zone_composite_index",
]

NUMERIC_COLUMNS = [
    "price_soles",
    "area_m2",
    "price_per_m2",
    "rooms",
    "bathrooms",
    "parking",
    "district_median_price_m2",
    "baseline_price_soles",
    "opportunity_score_baseline",
    "crime_index_zone",
    "urban_convenience_index",
    "zone_composite_index",
    "idh_2019",
    "pct_pobreza_total",
]

BOUNDED_COLUMNS = {
    "crime_index_zone": (0, 1),
    "urban_convenience_index": (0, 1),
    "zone_composite_index": (0, 1),
    "idh_2019": (0, 1),
    "pct_pobreza_total": (0, 100),
}


def parse_float(value):
    if value is None or value == "":
        return None
    try:
        number = float(value)
    except ValueError:
        return None
    if math.isnan(number) or math.isinf(number):
        return None
    return number


def percentile(values, pct):
    if not values:
        return None
    ordered = sorted(values)
    index = (len(ordered) - 1) * pct
    lower = math.floor(index)
    upper = math.ceil(index)
    if lower == upper:
        return ordered[int(index)]
    return ordered[lower] + (ordered[upper] - ordered[lower]) * (index - lower)


def fmt(value):
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:,.3f}"
    return str(value)


def read_rows(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def main():
    rows = read_rows(FEATURE_STORE)
    headers = rows[0].keys() if rows else []
    missing_required = [column for column in REQUIRED_COLUMNS if column not in headers]

    missing_counts = Counter()
    numeric_values = defaultdict(list)
    invalid_numeric = Counter()
    bounded_violations = Counter()
    positive_violations = Counter()
    district_counts = Counter()
    listing_ids = Counter()
    business_keys = Counter()

    for row in rows:
        district_counts[row.get("district", "")] += 1
        listing_ids[row.get("listing_id", "")] += 1
        business_keys[
            (
                row.get("address", "").strip().upper(),
                row.get("price_soles", ""),
                row.get("area_m2", ""),
            )
        ] += 1
        for column in headers:
            if row.get(column) in (None, ""):
                missing_counts[column] += 1
        for column in NUMERIC_COLUMNS:
            value = parse_float(row.get(column))
            if row.get(column) not in (None, "") and value is None:
                invalid_numeric[column] += 1
                continue
            if value is None:
                continue
            numeric_values[column].append(value)
            if column in {"price_soles", "area_m2", "price_per_m2", "district_median_price_m2", "baseline_price_soles"} and value <= 0:
                positive_violations[column] += 1
            if column in BOUNDED_COLUMNS:
                lower, upper = BOUNDED_COLUMNS[column]
                if value < lower or value > upper:
                    bounded_violations[column] += 1

    duplicate_listing_ids = sum(count for key, count in listing_ids.items() if key and count > 1)
    duplicate_business_keys = sum(count for key, count in business_keys.items() if key[0] and count > 1)

    lines = [
        "# Week 6 processed data validation",
        "",
        "Generated by `code/validate_processed_data.py` from `data/processed/listings_feature_store.csv`.",
        "",
        "## Structural checks",
        "",
        f"- Rows: {len(rows):,}",
        f"- Columns: {len(list(headers))}",
        f"- Missing required columns: {', '.join(missing_required) if missing_required else 'none'}",
        f"- Duplicate `listing_id` rows: {duplicate_listing_ids:,}",
        f"- Duplicate address/price/area candidate rows: {duplicate_business_keys:,}",
        f"- Districts represented: {len(district_counts):,}",
        "",
        "## Range and type checks",
        "",
        f"- Invalid numeric values: {sum(invalid_numeric.values()):,}",
        f"- Non-positive value violations in price/area fields: {sum(positive_violations.values()):,}",
        f"- Bounded-index violations: {sum(bounded_violations.values()):,}",
        "",
        "## Missingness by column",
        "",
        "| Column | Missing | Missing % |",
        "|---|---:|---:|",
    ]
    for column in headers:
        count = missing_counts[column]
        lines.append(f"| {column} | {count:,} | {count / len(rows) * 100:.2f}% |")

    lines.extend([
        "",
        "## Numeric summaries",
        "",
        "| Column | Count | Min | P25 | Median | P75 | Max |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ])
    for column in NUMERIC_COLUMNS:
        values = numeric_values[column]
        lines.append(
            f"| {column} | {len(values):,} | {fmt(min(values) if values else None)} | "
            f"{fmt(percentile(values, 0.25))} | {fmt(percentile(values, 0.50))} | "
            f"{fmt(percentile(values, 0.75))} | {fmt(max(values) if values else None)} |"
        )

    lines.extend([
        "",
        "## District coverage",
        "",
        "| District | Listings |",
        "|---|---:|",
    ])
    for district, count in district_counts.most_common():
        lines.append(f"| {district or 'MISSING'} | {count:,} |")

    lines.extend([
        "",
        "## Notes",
        "",
        "- Duplicate business-key rows are candidates only; repeated units in the same building can legitimately share address, price, and area.",
        "- BCRP fields are expected to be partially missing because the official series covers fewer districts than the Urbania listing set.",
    ])

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"validation report -> {OUTPUT}")


if __name__ == "__main__":
    main()
